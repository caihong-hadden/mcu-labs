/**
 * @file main_15f.c
 * @brief STC15F 系列平台 (蓝桥杯 CT107D 架构) - 点亮第二颗 LED
 * @details 硬件平台: STC15F2K60S2 / IAP15F2K61S2 开发板 (蓝桥杯 CT107D/CT107S)
 *          时钟频率: 11.0592MHz / 12.000MHz
 *          硬件控制:
 *          1. 蓝桥杯开发板外设总线通过 74HC138 译码器 + 74HC573 锁存器架构进行控制。
 *          2. 将 J13 跳线帽接在 IO 模式，P4.2 输出低电平 (P42 = 0) 开启 WR 门禁。
 *          3. 配置 74HC138 译码通道 Y4C (LED 锁存器): P27=1, P26=0, P25=0。
 *          4. 74HC573 锁存器的高电平有效 (LE=1) 处于透明导通状态。
 *          5. P0 端口输出低电平点亮板载 LED，L2 对应 P0.1 引脚:
 *             P0 = 0xFD (1111 1101B)，实现第二颗 LED (L2) 稳定点亮。
 */

#include <STC15F2K60S2.H>

/**
 * @brief 主函数
 */
void main(void)
{
    /* 1. 开启 74HC138 译码与 LED (Y4C) 锁存使能 */
    P42 = 0;    // WR 门禁使能 (J13 IO 模式)
    P27 = 1;
    P26 = 0;
    P25 = 0;    // Y4C 选通使能 (74HC573 LE 保持高电平透明传输)

    /* 2. 向 P0 端口写入数据: 0xFD (1111 1101B)，点亮 L2，熄灭其余指示灯 */
    P0 = 0xFD;

    while (1)
    {
        /* 主循环保持常亮 */
    }
}
