/**
 * @file dainzhen.c
 * @brief 8x8 LED 点阵屏底层点阵扫描驱动源文件
 * @details 硬件平台: STC15F2K60S2 (蓝桥杯 CT107D/CT107S)
 *          控制架构:
 *          采用 74HC138 译码器与 74HC573 锁存器分别锁存点阵行 (Y7C) 与点阵列 (Y6C)
 *          1. 消影: 选通 Y7C 输出全高电平 0xFF，避免扫描切换时产生拉丝/虚影;
 *          2. 行选 (阴极控制): 选通 Y7C，写入 ~(0x01 << X)，使对应行输出低电平有效;
 *          3. 列选 (阳极控制): 选通 Y6C，写入 (0x01 << Y)，使对应列输出高电平有效;
 *          4. 交叉点亮坐标 (X, Y) 处的点。
 */

#include "dianzhen.h"
#include <STC15F2K60S2.H>
#include "Delay.h"

void dianzhen(unsigned char X, unsigned char Y)
{
    /* 1. 消影处理: 选通 Y7C 输出全高电平熄灭行，消除视觉重影 */
    P27 = 1; P26 = 1; P25 = 1; // 选通 Y7C (111B)
    P0 = 0xFF;                  // 关闭所有段
    P27 = 0; P26 = 0; P25 = 0; // 锁存数据
	Delay(1);

    /* 2. 行选择 (Y7C 通道): 低电平有效，将第 X 位拉低 */
    P27 = 1; P26 = 1; P25 = 1;
    P0 = ~(0x01 << X);          // 按位取反，仅第 X 位输出 0
    P27 = 0; P26 = 0; P25 = 0; // 产生下降沿锁存行数据

    /* 3. 列选择 (Y6C 通道): 高电平有效，将第 Y 位拉高 */
    P27 = 1; P26 = 1; P25 = 0; // 选通 Y6C (110B)
    P0 = (0x01 << Y);           // 仅第 Y 位输出 1
    P27 = 0; P26 = 0; P25 = 0; // 产生下降沿锁存列数据
}
