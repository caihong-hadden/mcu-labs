/**
 * @file main.c
 * @brief STC15F2K60S2 蓝桥杯竞赛板载外设复位与关闭 (蓝桥杯关灯/消影例程)
 * @details 硬件平台: STC15F2K60S2 / IAP15F2K61S2 开发板 (蓝桥杯 CT107D/CT107S)
 *          时钟频率: 11.0592MHz / 12.000MHz
 *          功能说明:
 *          蓝桥杯开发板在上电初始状态下，74HC573 锁存器引脚可能处于不稳定或微亮状态。
 *          本程序将跳线 J13 置于 IO 模式 (P4.2 = 0 开启 WR 门禁)，
 *          选通 74HC138 的 Y4C (LED 锁存通道: P27=1, P26=0, P25=0)，
 *          向 P0 写入全高电平 0xFF，彻底关闭板载全部 8 颗 LED (L1~L8)，
 *          作为蓝桥杯赛题标准初始化模块。
 */

#include <STC15F2K60S2.H>

/**
 * @brief 主函数
 */
void main(void)
{
    /* 1. 开启 74HC138 译码器 WR 门禁 (J13 IO 模式) */
    P42 = 0;

    while (1)
    {
        /* 2. 选通 Y4C 通道 (LED 锁存使能: 100B) */
        P27 = 1;
        P26 = 0;
        P25 = 0;

        /* 3. P0 输出全高电平，关闭所有板载 LED */
        P0 = 0xFF;
    }
}
