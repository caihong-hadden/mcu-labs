/* USER CODE BEGIN 4 */
void HAL_HRTIM_RepetitionEventCallback(HRTIM_HandleTypeDef * hhrtim, uint32_t TimerIdx){
	if (TimerIdx == HRTIM_TIMERINDEX_TIMER_A)
	    {
		// ▼▼▼ 目視確認用：20,000回に1回だけLEDを反転させる ▼▼▼
		        static uint16_t led_counter = 0; // staticをつけて値を保持する

		        led_counter++;
		        if (led_counter >= 20000) // 20kHz ÷ 20000 = 1Hz (1秒に1回)
		        {
		            BSP_LED_Toggle(LED_GREEN);
		            led_counter = 0;
		        }
	        // 1. 位相を進める
	        phase_acc += phase_step;
	        if (phase_acc >= (float)LUT_SIZE)
	        {
	            phase_acc -= (float)LUT_SIZE;
	        }

	        // 2. 各相のインデックス計算 (120度 = LUT_SIZE / 3)
	        // インデックスは整数である必要がある
	        int idx_a = (int)phase_acc;
	        int idx_b = idx_a + (LUT_SIZE / 3);
	        int idx_c = idx_a + (2 * LUT_SIZE / 3);

	        // テーブル範囲内に丸める
	        if (idx_b >= LUT_SIZE) idx_b -= LUT_SIZE;
	        if (idx_c >= LUT_SIZE) idx_c -= LUT_SIZE;

	        // 3. デューティ比の計算 (Compare値)
	        // Up-Downモードの場合:
	        // Duty 50% = Period / 2
	        // Compare値 = Period * (1 + M * sin) / 2  ... (0中心の正弦波を 0~Periodにオフセット)

	        float center = (float)HRTIM_PERIOD_COUNTS / 2.0f;

	        // 相ごとのCompare値計算
	        uint16_t cmp_a = (uint16_t)(center * (1.0f + mod_index * sin_lut[idx_a]));
	        uint16_t cmp_b = (uint16_t)(center * (1.0f + mod_index * sin_lut[idx_b]));
	        uint16_t cmp_c = (uint16_t)(center * (1.0f + mod_index * sin_lut[idx_c]));

	        // 4. レジスタへ書き込み (次の周期で反映される)
	        __HAL_HRTIM_SETCOMPARE(hhrtim, HRTIM_TIMERINDEX_TIMER_A, HRTIM_COMPAREUNIT_1, cmp_a);
	        __HAL_HRTIM_SETCOMPARE(hhrtim, HRTIM_TIMERINDEX_TIMER_B, HRTIM_COMPAREUNIT_1, cmp_b);
	        __HAL_HRTIM_SETCOMPARE(hhrtim, HRTIM_TIMERINDEX_TIMER_C, HRTIM_COMPAREUNIT_1, cmp_c);

	        // もしfmを変えたらstepも更新する処理をここに入れるか，mainループで計算しておく
	        // (ここでは省略)
	    }
}
