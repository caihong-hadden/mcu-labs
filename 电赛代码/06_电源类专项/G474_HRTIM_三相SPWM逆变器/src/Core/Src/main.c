/***
 * @brief Initialize LUT
 */
void Init_Sine_LUT(void)
{
	//generate LUT
    for (int i = 0; i < LUT_SIZE; i++)
    {
        float theta = (2.0f * PI * (float)i) / (float)LUT_SIZE;
        sin_lut[i] = sinf(theta);
    }
}

