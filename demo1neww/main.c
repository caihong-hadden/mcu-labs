/**
 * @file main.c
 * @brief STC15F2K60S2 蓝桥杯板载 LED 关闭例程 (关灯复位)
 * @details 硬件平台: STC15F2K60S2 / IAP15F2K61S2 开发板 (蓝桥杯 CT107D/CT107S)
 *          时钟频率: 11.0592MHz / 12.000MHz
 *          底层控制逻辑:
 *          1. 选通 74HC138 译码器的 Y4 通道 (LED 锁存使能): P27=1, P26=0, P25=0。
 *          2. 向 P0 端口写入 0xFF (全部输出高电平)，使 8 颗 LED 阴极均为高电平而截止熄灭。
 *          3. 将 P4.2 输出高电平锁存数据，防止后续总线操作干扰 LED 显示。
 */

#include <STC15F2K60S2.H>

void main(void)
{
    /* 1. 选通 74HC138 的 Y4 通道 (LED 锁存通道) */
    P27 = 1;
    P26 = 0;
    P25 = 0;

    /* 2. 使能锁存控制 */
    P42 = 1;

    /* 3. 输出全高电平，关闭全部 8 颗指示灯 (L1~L8 全灭) */
    P0 = 0xFF;

    while (1)
    {
        /* 保持熄灭状态 */
    }
}
