/**
 * @file main.c
 * @brief STC15F2K60S2 蓝桥杯板载 LED 点亮基础例程 (点亮 L2)
 * @details 硬件平台: STC15F2K60S2 / IAP15F2K61S2 开发板 (蓝桥杯 CT107D/CT107S)
 *          时钟频率: 11.0592MHz / 12.000MHz
 *          底层控制逻辑:
 *          1. 蓝桥杯开发板外设采用 74HC138 译码器 + 74HC573 锁存器架构。
 *          2. 将跳线 J13 置于 IO 模式，P4.2 输出低电平使能 74HC02 或非门输出 (WR 门禁开启)。
 *          3. 设置 74HC138 输入端: P27=1, P26=0, P25=0 (选择 Y4 通道)。
 *             译码器 Y4 输出低电平，经或非门反相后产生高电平脉冲使能 74HC573 (LE=1)。
 *          4. P0.1 置低电平 (P01 = 0)，导通点亮指示灯 L2。
 */

#include <STC15F2K60S2.H>

void main(void)
{
    /* 1. 打开 74HC138 译码与 LED (Y4C) 锁存使能 */
    P27 = 1;
    P26 = 0;
    P25 = 0;    // 选择 Y4 译码通道 (100B)
    P42 = 0;    // WR 门禁使能 (J13 IO 模式)

    /* 2. 点亮指示灯 L2 (P0.1 输出低电平) */
    P01 = 0;

    while (1)
    {
        /* 保持常亮状态 */
    }
}
